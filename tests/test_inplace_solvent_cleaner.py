import importlib.util
import sys
from pathlib import Path

import pytest

SCRIPT = Path(__file__).parents[1] / "scripts" / "clean_constructed_mof_solvent.py"
SPEC = importlib.util.spec_from_file_location("clean_constructed_mof_solvent", SCRIPT)
assert SPEC is not None and SPEC.loader is not None
cleaner = importlib.util.module_from_spec(SPEC)
sys.modules[SPEC.name] = cleaner
SPEC.loader.exec_module(cleaner)
MARKER = cleaner.MARKER
transform_cif = cleaner.transform_cif


def cif_text(atoms, bonds, block="m_node1") -> bytes:
    atom_rows = "".join(
        f"{label} {symbol} 0.0 0.0 0.0 0.00000\n"
        for label, symbol in atoms
    )
    bond_rows = "".join(
        f"{left} {right} {distance:.3f} . S\n"
        for left, right, distance in bonds
    )
    return (
        "# Generated by mofbb.\n"
        f"#     Node 0, Type 0, BuildingBlock: {block}, "
        "# of connection points: 4\n"
        "data_test\n"
        "loop_\n"
        "_atom_site_label\n"
        "_atom_site_type_symbol\n"
        "_atom_site_fract_x\n"
        "_atom_site_fract_y\n"
        "_atom_site_fract_z\n"
        "_atom_type_partial_charge\n"
        f"{atom_rows}"
        "loop_\n"
        "_geom_bond_atom_site_label_1\n"
        "_geom_bond_atom_site_label_2\n"
        "_geom_bond_distance\n"
        "_geom_bond_site_symmetry_2\n"
        "_ccdc_geom_bond_type\n"
        f"{bond_rows}"
    ).encode()


def test_transform_removes_terminal_aqua_and_its_bonds() -> None:
    source = cif_text(
        [("Zn0", "Zn"), ("O1", "O"), ("H2", "H"), ("H3", "H")],
        [
            ("Zn0", "O1", 2.1),
            ("O1", "H2", 0.98),
            ("O1", "H3", 0.98),
            ("Zn0", "H3", 1.7),
        ],
    )

    result = transform_cif(source, {"m_node1": 3})

    assert result.removed_atoms == 3
    assert result.removed_bonds == 4
    assert result.content is not None
    assert MARKER in result.content
    assert b"Zn0 Zn" in result.content
    assert b"O1 O" not in result.content
    assert b"Zn0 O1" not in result.content


def test_transform_removes_split_oxygen_sites() -> None:
    source = cif_text(
        [("Cu0", "Cu"), ("O1", "O"), ("O2", "O")],
        [("Cu0", "O1", 2.218), ("Cu0", "O2", 2.218), ("O1", "O2", 0.889)],
    )

    result = transform_cif(source, {"m_node1": 2})

    assert result.removed_atoms == 2
    assert result.removed_bonds == 3
    assert result.content is not None
    assert b"Cu0 Cu" in result.content
    assert b"O1 O" not in result.content
    assert b"O2 O" not in result.content


@pytest.mark.parametrize(
    ("atoms", "bonds"),
    [
        ([("Zn0", "Zn"), ("O1", "O")], [("Zn0", "O1", 1.8)]),
        (
            [("Zn0", "Zn"), ("O1", "O"), ("H2", "H")],
            [("Zn0", "O1", 2.0), ("O1", "H2", 0.98)],
        ),
        (
            [
                ("Zn0", "Zn"),
                ("Zn1", "Zn"),
                ("O2", "O"),
                ("H3", "H"),
                ("H4", "H"),
            ],
            [
                ("Zn0", "O2", 2.1),
                ("Zn1", "O2", 2.1),
                ("O2", "H3", 0.98),
                ("O2", "H4", 0.98),
            ],
        ),
        (
            [("Cu0", "Cu"), ("O1", "O"), ("O2", "O")],
            [("Cu0", "O1", 2.0), ("Cu0", "O2", 2.0), ("O1", "O2", 1.2)],
        ),
    ],
    ids=["oxo", "hydroxide", "bridging-water", "real-oxygen-bond"],
)
def test_transform_preserves_framework_oxygen_motifs(atoms, bonds) -> None:
    source = cif_text(atoms, bonds, block="m_node_clean")

    with pytest.raises(ValueError, match="no expected contaminated node"):
        transform_cif(source, {})


def test_transform_rejects_candidate_count_mismatch() -> None:
    source = cif_text(
        [("Cu0", "Cu"), ("O1", "O"), ("O2", "O")],
        [("Cu0", "O1", 2.218), ("Cu0", "O2", 2.218), ("O1", "O2", 0.889)],
    )

    with pytest.raises(ValueError, match="candidate count does not match"):
        transform_cif(source, {"m_node1": 4})


def test_transform_is_idempotent_after_marker() -> None:
    assert transform_cif(MARKER + b"data_test\n", {"m_node1": 3}).status == (
        "already_clean"
    )
