"""Assembled framework model and CIF writer."""

import copy
from pathlib import Path

import numpy as np
from ase.cell import Cell

from mofbb.compose.connectivity import (
    bond_arrays,
    mic_shifts,
    validate_3d_connectivity,
)


class Framework:
    """Hold a fully assembled periodic framework and write it to CIF."""

    def __init__(self, atoms, bonds, bond_types, info, wrap=True, *, bond_shifts=None):
        """Store copies of the geometry, bonds, and metadata."""
        self.atoms = atoms.copy()
        if bond_shifts is None:
            bond_shifts = mic_shifts(atoms, bonds)
        pairs, shifts = bond_arrays(len(atoms), bonds, bond_shifts)
        self.bonds = pairs.copy()
        self.bond_shifts = shifts.copy()
        self.bond_types = copy.deepcopy(bond_types)
        self.info = copy.deepcopy(info)

        if wrap:
            self.wrap()

    def wrap(self):
        """Fold atoms into ``[0, 1)`` using only lattice translations."""

        scaled = self.atoms.get_scaled_positions(wrap=False)
        images = np.floor(scaled).astype(int)
        self.bond_shifts += images[self.bonds[:, 1]] - images[self.bonds[:, 0]]
        self.atoms.set_scaled_positions(scaled - images)

    def validate_3d(self):
        """Check current coordinates against the intended periodic bond graph."""
        quality = validate_3d_connectivity(
            self.atoms,
            self.bonds,
            self.bond_shifts,
            bond_scale=self.info.get("scale", 1.2),
        )
        self.info.update(quality)
        return quality

    def write_cif(self, filename):
        """Write the framework to a CIF file."""
        path = Path(filename).resolve()
        if path.suffix != ".cif":
            path = path.with_suffix(".cif")
        path.parent.mkdir(parents=True, exist_ok=True)
        stem = path.stem.replace(" ", "_")

        # Check the serialized geometry: rounding must not break a bridge.
        cell_parameters = np.round(self.atoms.cell.cellpar(), 3)
        cell = np.asarray(Cell.fromcellpar(cell_parameters))
        rounded = np.round(self.atoms.get_scaled_positions(wrap=False), 10)
        frac_coords = np.mod(rounded, 1.0)
        atom_images = np.rint(rounded - frac_coords).astype(int)
        left, right = self.bonds.T
        shifts = (
            self.bond_shifts
            + atom_images[right]
            - atom_images[left]
        )
        images = shifts + 5  # CIF encodes the zero image as 555.
        if np.any((images < 0) | (images > 9)):
            raise ValueError("Bond image cannot be represented by a CIF 1_abc code.")
        if self.info.get("require_3d", False):
            serialized = self.atoms.copy()
            serialized.set_cell(cell)
            serialized.set_scaled_positions(frac_coords)
            self.info.update(
                validate_3d_connectivity(
                    serialized, self.bonds, shifts,
                    bond_scale=self.info.get("scale", 1.2),
                )
            )

        with path.open("w") as f:
            f.write("# Generated by mofbb.\n")
            topology = self.info.get("topology")
            if topology is not None:
                f.write(f"# {topology}\n")
                f.write("# Building blocks:\n")
                for i in topology.node_idx:
                    t = topology.node_types[i]
                    bb = self.info["located_bbs"][i]
                    f.write(f"#     Node {i}, Type {t}, {bb}\n")
                for i in topology.edge_idx:
                    t = tuple(topology.edge_types[i])
                    bb = self.info["located_bbs"][i]
                    f.write(f"#     Edge {i}, Type {t}, {bb}\n")
                loss = self.info["geometry_optimization_loss"]
                f.write(f"# Geometry optimization loss: {loss:.3f}\n")
                f.write(f"# Max RMSD: {self.info['max_rmsd']:.3f}\n")
                f.write(f"# Mean RMSD: {self.info['mean_rmsd']:.3f}\n")
            elif self.info.get("decomposition_dir"):
                f.write(
                    "# Reconstructed from "
                    f"{self.info['decomposition_dir']}\n"
                )

            f.write("data_{}\n".format(stem))

            f.write("_symmetry_space_group_name_H-M    P1\n")
            f.write("_symmetry_Int_Tables_number       1\n")
            f.write("_symmetry_cell_setting            triclinic\n")

            f.write("loop_\n")
            f.write("_symmetry_equiv_pos_as_xyz\n")
            f.write("'x, y, z'\n")

            (
                a,
                b,
                c,
                alpha,
                beta,
                gamma,
            ) = cell_parameters

            f.write("_cell_length_a     {:.3f}\n".format(a))
            f.write("_cell_length_b     {:.3f}\n".format(b))
            f.write("_cell_length_c     {:.3f}\n".format(c))
            f.write("_cell_angle_alpha  {:.3f}\n".format(alpha))
            f.write("_cell_angle_beta   {:.3f}\n".format(beta))
            f.write("_cell_angle_gamma  {:.3f}\n".format(gamma))

            f.write("loop_\n")
            f.write("_atom_site_label\n")
            f.write("_atom_site_type_symbol\n")
            f.write("_atom_site_fract_x\n")
            f.write("_atom_site_fract_y\n")
            f.write("_atom_site_fract_z\n")
            f.write("_atom_type_partial_charge\n")

            symbols = self.atoms.symbols
            charges = self.atoms.get_initial_charges()

            for i, (sym, pos, charge) in enumerate(zip(symbols, frac_coords, charges)):
                label = "{}{}".format(sym, i)
                f.write(
                    "{} {} {:.10f} {:.10f} {:.10f} {:.5f}\n".format(
                        label,
                        sym,
                        *pos,
                        charge,
                    )
                )

            f.write("loop_\n")
            f.write("_geom_bond_atom_site_label_1\n")
            f.write("_geom_bond_atom_site_label_2\n")
            f.write("_geom_bond_distance\n")
            f.write("_geom_bond_site_symmetry_2\n")
            f.write("_ccdc_geom_bond_type\n")

            vectors = (frac_coords[right] - frac_coords[left] + shifts) @ cell
            distances = np.linalg.norm(vectors, axis=1)

            for (i, j), bond_type, distance, image in zip(
                self.bonds,
                self.bond_types,
                distances,
                images,
                strict=True,
            ):

                symmetry = "." if (image == 5).all() else "1_{}{}{}".format(*image)
                f.write(
                    f"{symbols[i]}{i} {symbols[j]}{j} "
                    f"{distance:.3f} {symmetry} {bond_type}\n"
                )
        return path
