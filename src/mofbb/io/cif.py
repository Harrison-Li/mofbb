'''
CIF readers and serializers for structures and periodic bonded frameworks.
'''

from __future__ import annotations

from collections.abc import Iterator
from pathlib import Path
import re
import shlex

import ase
import ase.io
from ase.geometry import cell_to_cellpar
from ase.cell import Cell
import numpy as np

from mofbb.common.connectivity import validate_3d_connectivity



def write_cif(path: str | Path, structure: ase.Atoms | Framework) -> Path:
    '''
    Write atoms or a bonded framework to a CIF file.

    Framework output includes periodic bonds and assembly metadata. Empty atom
    selections produce a cell-only CIF. If the framework requires 3D connectivity,
    the rounded output geometry is checked and its info dictionary is updated.

    Args:
        path (str or Path):
            Output location; the suffix is replaced with .cif and parents are created.
        structure (ase.Atoms or Framework):
            Atoms to serialize, or a framework with explicit bonds and cell shifts.

    Returns:
        The resolved output Path.
    '''
    path = Path(path).resolve().with_suffix(".cif")
    if isinstance(structure, ase.Atoms):
        atoms = structure
        path.parent.mkdir(parents=True, exist_ok=True)
        if len(atoms):
            ase.io.write(path, atoms, format="cif", wrap=False)
            return path

        name = re.sub(r"[^A-Za-z0-9_]", "_", path.stem)
        lines = [f"data_{name}"]
        if atoms.cell.rank == 3:
            a, b, c, alpha, beta, gamma = cell_to_cellpar(atoms.cell)
            lines += [
                f"_cell_length_a {a:.15g}",
                f"_cell_length_b {b:.15g}",
                f"_cell_length_c {c:.15g}",
                f"_cell_angle_alpha {alpha:.15g}",
                f"_cell_angle_beta {beta:.15g}",
                f"_cell_angle_gamma {gamma:.15g}",
                "_space_group_name_H-M_alt 'P 1'",
            ]
        path.write_text("\n".join([*lines, "_mofbb_atom_count 0", ""]), encoding="utf-8")
        return path

    atoms = structure.atoms
    bonds = structure.bonds
    bond_types = structure.bond_types
    info = structure.info
    # Check the serialized geometry: rounding must not break a bridge.
    cell_parameters = np.round(atoms.cell.cellpar(), 3)
    cell = np.asarray(Cell.fromcellpar(cell_parameters))
    rounded = np.round(atoms.get_scaled_positions(wrap=False), 10)
    frac_coords = np.mod(rounded, 1.0)
    atom_images = np.rint(rounded - frac_coords).astype(int)
    left, right = bonds.T
    shifts = (
        structure.bond_shifts
        + atom_images[right]
        - atom_images[left]
    )
    images = shifts + 5  # CIF encodes the zero image as 555.
    if np.any((images < 0) | (images > 9)):
        raise ValueError("Bond image cannot be represented by a CIF 1_abc code.")
    if info.get("require_3d", False):
        serialized = atoms.copy()
        serialized.set_cell(cell)
        serialized.set_scaled_positions(frac_coords)
        info.update(
            validate_3d_connectivity(
                serialized, bonds, shifts,
                bond_scale=info.get("scale", 1.2),
            )
        )

    path.parent.mkdir(parents=True, exist_ok=True)
    stem = path.stem.replace(" ", "_")
    with path.open("w") as f:
        f.write("# Generated by mofbb.\n")
        topology = info.get("topology")
        if topology is not None:
            f.write(f"# {topology}\n")
            f.write("# Building blocks:\n")
            for i in topology.node_idx:
                t = topology.node_types[i]
                bb = info["located_bbs"][i]
                f.write(f"#     Node {i}, Type {t}, {bb}\n")
            for i in topology.edge_idx:
                t = tuple(topology.edge_types[i])
                bb = info["located_bbs"][i]
                f.write(f"#     Edge {i}, Type {t}, {bb}\n")
            loss = info["geometry_optimization_loss"]
            f.write(f"# Geometry optimization loss: {loss:.3f}\n")
            f.write(f"# Max RMSD: {info['max_rmsd']:.3f}\n")
            f.write(f"# Mean RMSD: {info['mean_rmsd']:.3f}\n")
        elif info.get("decomposition_dir"):
            f.write(
                "# Reconstructed from "
                f"{info['decomposition_dir']}\n"
            )

        f.write("data_{}\n".format(stem))

        f.write("_symmetry_space_group_name_H-M    P1\n")
        f.write("_symmetry_Int_Tables_number       1\n")
        f.write("_symmetry_cell_setting            triclinic\n")

        f.write("loop_\n")
        f.write("_symmetry_equiv_pos_as_xyz\n")
        f.write("'x, y, z'\n")

        (
            a,
            b,
            c,
            alpha,
            beta,
            gamma,
        ) = cell_parameters

        f.write("_cell_length_a     {:.3f}\n".format(a))
        f.write("_cell_length_b     {:.3f}\n".format(b))
        f.write("_cell_length_c     {:.3f}\n".format(c))
        f.write("_cell_angle_alpha  {:.3f}\n".format(alpha))
        f.write("_cell_angle_beta   {:.3f}\n".format(beta))
        f.write("_cell_angle_gamma  {:.3f}\n".format(gamma))

        f.write("loop_\n")
        f.write("_atom_site_label\n")
        f.write("_atom_site_type_symbol\n")
        f.write("_atom_site_fract_x\n")
        f.write("_atom_site_fract_y\n")
        f.write("_atom_site_fract_z\n")
        f.write("_atom_type_partial_charge\n")

        symbols = atoms.symbols
        charges = atoms.get_initial_charges()

        for i, (sym, pos, charge) in enumerate(zip(symbols, frac_coords, charges)):
            label = "{}{}".format(sym, i)
            f.write(
                "{} {} {:.10f} {:.10f} {:.10f} {:.5f}\n".format(
                    label,
                    sym,
                    *pos,
                    charge,
                )
            )

        f.write("loop_\n")
        f.write("_geom_bond_atom_site_label_1\n")
        f.write("_geom_bond_atom_site_label_2\n")
        f.write("_geom_bond_distance\n")
        f.write("_geom_bond_site_symmetry_2\n")
        f.write("_ccdc_geom_bond_type\n")

        vectors = (frac_coords[right] - frac_coords[left] + shifts) @ cell
        distances = np.linalg.norm(vectors, axis=1)

        for (i, j), bond_type, distance, image in zip(
            bonds,
            bond_types,
            distances,
            images,
            strict=True,
        ):

            symmetry = "." if (image == 5).all() else "1_{}{}{}".format(*image)
            f.write(
                f"{symbols[i]}{i} {symbols[j]}{j} "
                f"{distance:.3f} {symmetry} {bond_type}\n"
            )
    return path



def cif_loops(path: Path) -> Iterator[tuple[list[str], list[list[str]]]]:
    '''
    Read line-based CIF loops and split quoted values.

    Args:
        path (Path):
            UTF-8 CIF file with each data row on one line.

    Returns:
        An iterator of (headers, rows) pairs, where both headers and row values
        are strings. This helper does not parse multiline CIF text fields.
    '''
    lines = path.read_text(encoding="utf-8").splitlines()
    i = 0
    while i < len(lines):
        if lines[i].strip() != "loop_":
            i += 1
            continue

        i += 1
        headers: list[str] = []
        while i < len(lines) and lines[i].strip().startswith("_"):
            headers.append(lines[i].strip())
            i += 1

        rows: list[list[str]] = []
        while i < len(lines):
            stripped = lines[i].strip()
            if (
                not stripped
                or stripped == "loop_"
                or stripped.startswith(("_", "data_"))
            ):
                break
            if not stripped.startswith("#"):
                rows.append(shlex.split(stripped))
            i += 1

        yield headers, rows


def atom_label_to_index(
    loops: list[tuple[list[str], list[list[str]]]],
) -> dict[str, int]:
    '''
    Map labels in the first atom-site loop to their row indices.

    Args:
        loops (list of tuple):
            Parsed (headers, rows) pairs from cif_loops.

    Returns:
        A dictionary of labels to zero-based atom indices, or an empty dictionary
        if no atom-site label loop is present.
    '''
    for headers, rows in loops:
        if "_atom_site_label" not in headers:
            continue
        label_index = headers.index("_atom_site_label")
        return {
            row[label_index]: atom_index
            for atom_index, row in enumerate(rows)
            if len(row) > label_index
        }
    return {}


def geom_bond_loop(
    loops: list[tuple[list[str], list[list[str]]]],
) -> tuple[list[str], list[list[str]]] | None:
    '''
    Find the first CIF loop that names both atoms of each bond.

    Args:
        loops (list of tuple):
            Parsed (headers, rows) pairs from cif_loops.

    Returns:
        The matching (headers, rows) pair, or None if it is absent.
    '''
    for headers, rows in loops:
        if (
            "_geom_bond_atom_site_label_1" in headers
            and "_geom_bond_atom_site_label_2" in headers
        ):
            return headers, rows
    return None


def atom_index_from_label(label: str, label_to_index: dict[str, int]) -> int | None:
    '''
    Resolve an atom label, falling back to its trailing integer.

    Args:
        label (str):
            CIF atom label to look up.
        label_to_index (dict[str, int]):
            Known labels and their zero-based atom indices.

    Returns:
        The mapped index or trailing integer without adjusting its base; None
        if neither is available.
    '''
    if label in label_to_index:
        return label_to_index[label]
    match = re.search(r"(\d+)$", label)
    if match is None:
        return None
    return int(match.group(1))


def site_symmetry_offset(symmetry: str) -> np.ndarray:
    '''
    Decode the cell translation in a CIF symmetry code such as 1_565.

    The symmetry-operation number is ignored; this helper only reads translation.

    Args:
        symmetry (str):
            CIF site-symmetry code. Missing or unrecognized codes mean zero shift.

    Returns:
        A (3,) integer array with 5 subtracted from each encoded digit.
    '''
    if symmetry in {".", "?", ""}:
        return np.zeros(3, dtype=int)
    match = re.fullmatch(r"\d_([0-9])([0-9])([0-9])", symmetry)
    if match is None:
        return np.zeros(3, dtype=int)
    return np.array([int(value) - 5 for value in match.groups()], dtype=int)


